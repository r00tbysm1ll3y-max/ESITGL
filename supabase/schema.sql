-- 1. Buat Tabel: ATHLETES (Data Anggota / Atlet Esports Trenggalek)
CREATE TABLE IF NOT EXISTS public.athletes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    
    -- Informasi Akun SIMCO
    username TEXT,
    password_hash TEXT,
    
    -- Data Pribadi
    full_name TEXT NOT NULL,
    status_pekerjaan TEXT DEFAULT 'PELAJAR', -- 'PELAJAR' atau 'UMUM'
    jenjang TEXT,                          -- 'SMP', 'SMA', 'UMUM', dsb.
    institution TEXT NOT NULL,             -- Nama Sekolah atau Tempat Kerja
    agama TEXT,
    tempat_lahir TEXT,
    tanggal_lahir TEXT,                    -- Format DD-MM-YYYY
    jenis_kelamin TEXT,                    -- 'Laki-laki' atau 'Perempuan'
    
    -- Kontak & Domisili
    alamat TEXT,
    rt TEXT,
    rw TEXT,
    kodepos TEXT,
    desa TEXT,
    kecamatan TEXT,
    kabupaten TEXT DEFAULT 'Kabupaten Trenggalek',
    provinsi TEXT DEFAULT 'Jawa Timur',
    whatsapp TEXT NOT NULL,
    email TEXT,
    
    -- Data Game & Prestasi
    nickname TEXT NOT NULL,
    game_id TEXT NOT NULL,
    division TEXT NOT NULL,                -- 'MLBB', 'Free Fire', 'PUBG Mobile', 'eFootball'
    team_name TEXT DEFAULT 'Individu / Non-Tim',
    points INTEGER DEFAULT 0,
    status TEXT DEFAULT 'pending' CHECK (status IN ('pending', 'verified', 'rejected')),
    avatar_url TEXT,
    
    persetujuan BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

-- Indexing
CREATE INDEX IF NOT EXISTS idx_athletes_division ON public.athletes(division);
CREATE INDEX IF NOT EXISTS idx_athletes_status ON public.athletes(status);
CREATE INDEX IF NOT EXISTS idx_athletes_points ON public.athletes(points DESC);
CREATE INDEX IF NOT EXISTS idx_athletes_whatsapp ON public.athletes(whatsapp);

-- 2. Buat Tabel: EVENTS (Jadwal Kejuaraan & Seleksi)
CREATE TABLE IF NOT EXISTS public.events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    division TEXT NOT NULL,
    date TEXT NOT NULL,
    location TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'Upcoming' CHECK (status IN ('Upcoming', 'Ongoing', 'Selesai')),
    description TEXT,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

-- 3. Buat Tabel: NEWS (Berita & Informasi Resmi)
CREATE TABLE IF NOT EXISTS public.news (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    category TEXT NOT NULL CHECK (category IN ('Turnamen', 'Pengumuman', 'Pelatihan', 'Prestasi')),
    date TEXT NOT NULL,
    excerpt TEXT,
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

